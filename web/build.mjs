import { build } from 'vite';
import { cp, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { validatePackage } from './scripts/validate-data.mjs';
import { verifyDist } from './scripts/verify-dist.mjs';
import { validateRegions } from './scripts/validate-regions.mjs';
process.chdir(fileURLToPath(new URL('.', import.meta.url)));
await validatePackage('data', { publicOnly: true });
await validateRegions('regions');
await build();
await cp('data', 'dist/data', { recursive: true });
await cp('regions', 'dist/regions', { recursive: true });
await writeFile('dist/.nojekyll', '');
await verifyDist('dist');
console.log('AquaClima: pacote íntegro e aplicação estática compilada em web/dist.');
